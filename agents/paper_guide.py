"""论文写作规范 - 从数模 skill 模板与优秀论文范例提炼。

这些规范注入 WriterAgent 的 system prompt，保证生成的论文
符合国赛/美赛获奖论文的标准结构与表述。
"""

# 论文整体结构规范（对应 skill 默认模板 + 优秀范例共同特征）
STRUCTURE_GUIDE = """\
【论文整体结构规范】
一篇规范的高分数模论文应包含以下章节（按序）：
1. 摘要（单独成页，核心）
2. 问题重述（含问题背景 + 问题分析，分小题说明解决思路）
3. 模型假设（5-8条，每条说明合理性）
4. 符号说明（表格：符号|含义|单位，按模型分组）
5. 模型的建立与求解（核心，按子问题分节，每个子问题包含：模型建立+求解+结果）
6. 模型的检验/灵敏度分析（验证鲁棒性，与第5章不重复）
7. 模型的评价与推广（优点/缺点/推广）
8. 参考文献（GB/T 7714 格式）

【关键：章节不重复】
- 第5章每个子问题的末尾只写"求解方法"和"结果表格"，不写灵敏度分析
- 第6章专门写灵敏度分析：选2-3个关键参数，做单因素轮换实验，给出稳定性结论
- 如果第5章某个子问题有自己的鲁棒性测试（如问题4），在该子问题内简要提及，但详细分析放到第6章
- 严禁第5章和第6章内容重复！第5章=建模+求解+结果，第6章=灵敏度分析

【数据合理性规则】
- 如果模型输出负值（如负需求、负价格），必须在文中说明并处理（取绝对值/截断为0/标注异常）
- 表格中不允许出现"请填入"等占位符文字
- 所有数值必须有物理含义，不能出现无意义的极大/极小值

【公式规范】
- 每个独立公式（$$...$$块）由系统统一连续编号 (1),(2),...，正文**不要**手写具体式号
- 正文引用公式时用"上式""前述公式"等表述，不要写"式(3)"（编号由系统生成，手写会对不上）
- 公式前后各空一行；首次出现的公式需附文字说明各变量含义

【结果呈现规范】
- 每个子问题求解结束后，用汇总表格呈现最优方案（决策变量 | 最优值）
- 多子问题之间存在递进关系时，做对比分析（如"相比问题1，遮蔽时长提升约X倍"）
- 多弹/多机协同问题需说明协同机制（如"首尾衔接""早/中/晚分时段接力"）

【语言与排版规范】
- 全文使用第三人称或无人称表述（"本文建立了…"而非"我建立了…"）
- 专业术语首次出现时附英文全称，如"烟幕干扰弹（Smoke Interference Projectile）"
- 数值保留适当小数位（长度精确到0.1，时间精确到0.01，性能指标保留2-4位有效数字）
- 避免口语化表述（"大概""差不多"），统一用"约""近似"
- 每个子问题的小节标题格式统一（如"问题分析/模型建立/模型求解与结果"），不自行编号

【输出纪律——必须严格遵守】
- 只输出论文正文内容，**禁止**输出任何设计思路、设计说明、创作意图、元评论或自我解释
- **禁止**出现以下形式的内容："符号设计说明与反思"、"我将..."、"我选择...因为..."、"我考虑到..."、"设计说明"、"写作思路"、"反思"
- 符号说明表只包含：符号、含义、单位三列，**不附加**任何解释性注释或设计说明
- 直接陈述内容，不使用自我指涉性过渡语（如"本文将..."可以，但"我之所以这样设计是因为..."禁止）
"""

# 摘要写作规范（从 RGV 范例摘要提炼）
ABSTRACT_GUIDE = """\
【摘要写作规范】目标：300-500字内让评委看懂你做了什么、怎么做的、得到什么。
结构：
1. 开篇一句：本文针对【XX问题】，建立了【XX模型】/研究了【XX问题】（1-2句话，不超3句）
2. 分小题说明：按"问题1→问题2→…→问题N"顺序，针对任务X，我们【做了什么分析/建模】，
   采用【XX方法】，得到【具体数值结果】（每项1-2句）
3. 结尾：总结模型优点（如求解效率高、物理意义明确、鲁棒性强等）与灵敏度分析结论
4. 最后单独一行输出关键词：3-5个，按重要性降序，用领域标准术语，格式"关键词：XXX、XXX、XXX"
要求：
- 每个任务都要出现【具体数字结果】（如"最大产量382"、"遮蔽时长26.62s"），不要只写方法
- 摘要中不得出现公式编号引用（如"式(5)"），关键结论用文字或数值直接表述
- 分任务叙述，逻辑递进（任务一理论→任务二建模→任务三扩展）
- 语言精炼、学术化，避免口语
"""

# 问题分析规范（总述→难点→技术路线→递进）
ANALYSIS_GUIDE = """\
【问题分析规范】
一、总述：用一段话概括本题的学科分类与数学本质（如"运动学仿真 + 几何遮蔽判定 + 组合优化"）
二、核心难点：以编号列表列出 3-5 个核心难点，每项包含：难点名称、困难原因、拟采用的解决思路
三、总体技术路线：用一段说明整体方法框架（如"物理仿真作评估、网格搜索与贪心组合作优化"）
四、子问题递进分析：说明各子问题从简到难的递进关系（如"单弹→多弹→多机协同"的层次设计），
   再逐题说明数学本质与求解思路
要求：体现对问题的深入理解，避免简单重复题目信息
"""

# 模型建立与求解规范（从模板 4/5 章提炼）
MODEL_SECTION_GUIDE = """\
【模型建立与求解规范】每个子问题按以下四段式展开：
一、问题分析：分析该问题的数学本质，说明为什么选择该模型
二、模型选择：说明模型适用性、优点，可引用参考文献
三、数学模型：定义变量→目标函数→约束条件，公式用LaTeX编号
四、模型求解：说明算法步骤（分步列出）、参数设置、编程实现要点
【结果展示规范】
- 结果用表格呈现（指标|数值）
- 表格下方配文字解读（"由表X可知..."）
- 有图时插入并说明
【重要：不要在第5章写灵敏度分析！】
- 第5章每个子问题只写"建模+求解+结果"
- 如果子问题本身包含鲁棒性测试（如问题4），在该子问题内简要提及即可
- 详细灵敏度分析统一放到第6章
"""

# 灵敏度/稳健性分析规范
SENSITIVITY_GUIDE = """\
【灵敏度分析规范（第6章专用）】
重要：第6章只写灵敏度分析，不要重复第5章的建模/求解内容！

结构：
一、灵敏度分析设计：说明选取哪些参数、变化范围、评价指标
二、单因素轮换实验：每个参数单独扰动±10%~±20%，用表格呈现结果
三、综合分析：哪个参数最敏感，给出稳定性结论和建议

选取参数原则：
- 选模型中直接影响结果的2-3个关键参数（如成本系数、容量、权重）
- 不要选算法超参数（如种群大小、迭代次数）
- 每个参数给出物理含义和变化范围

注意：
- 第5章的问题4如果涉及鲁棒性测试，可以简要提及，但详细分析放到第6章
- 灵敏度分析的结论要与第5章的数值结果呼应，但不要重复第5章的内容
"""

# 模型评价与推广规范
EVALUATION_GUIDE = """\
【模型评价与推广规范】
一、模型优点（3-5点）：如模型通用性强、计算高效、结果准确、可扩展
二、模型缺点（2-3点）：如依赖数据质量、假设简化、计算开销
三、模型推广：说明可迁移到哪些类似场景（如共享汽车、快递柜调度）
"""

# ---- 人类写作风格规则（去AI化，参考 BypassAIGC/WRITING.md 策略） ----
HUMAN_STYLE_GUIDE = """
## 人类写作风格（使论文自然化，避免AI痕迹）

你写的每一句话都要像一个真实参赛队员在截止前熬夜写出来的——有紧迫感、有口语化痕迹、偶尔不那么"完美"。

1. 动词扩展（不要短动词直接接宾语，要拉长过程描述）：
   - "本文构建了…" → "本文从xxx出发，尝试构建了…"
   - "采用PSO…" → "借助粒子群优化（PSO）的全局搜索能力来标定…"
   - "利用DEM数据…" → "凭借高精度DEM数据提供的空间属性信息…"
   - "分析结果表明…" → "对结果进行深入分析后发现…"

2. 系统替换高频AI词汇（每出现一次就换一个说法）：
   - "通过" → "借助/依靠/凭借/经由"
   - "使用/采用" → "运用/选用/把…作为…来使用"
   - "基于" → "鉴于/凭借/在…的基础上"
   - "利用" → "借助/运用/凭借"
   - "和/及/与" → "以及（三者以上并列时）"
   - "提升/提高" → "得到进一步的提升/有了明显的改善"
   - "构建" → "搭建/建立/设计"
   - "实现" → "做到了/完成了/得以实现"

3. 插入自然助词（增加句子饱满度，模拟真人写作）：
   - 适当添加"的""地""所""会""可以""方面""其中""了""这个""当中"
   - "式(1)为…" → "式(1)所描述的正是…"

4. 禁止AI典型套话（出现就扣分）：
   - 不要每段开头都用"首先…其次…再次…最后…"
   - 不要频繁用"综上所述""总而言之""值得注意的是"
   - 不要用"本文构建了…一体化框架"这种万能句式
   - 每页"本文"不超过2次
   - 不要用"一方面…另一方面…"

5. 句式变化（长短交替，模拟真人节奏）：
   - 有的段落只有3行，有的段落8行
   - 偶尔用设问句引入下文："那么，如何处理xxx问题呢？"
   - 适当使用破折号做插入语
   - 偶尔一句话独立成段（强调效果）

6. 不确定语（避免全篇肯定语气，像真人一样留余地）：
   - "可能""一定程度上""在合理范围内""可以认为"
   - "该方法在xxx条件下表现较好"
   - "不排除xxx的可能性"
   - "从结果来看，xxx"

7. 引用自然化（不要"xxx[1]"紧贴）：
   - 用"xxx等[1]""文献[1]指出""根据xxx的研究[1]"
   - "正如xxx所讨论的那样[1]"
   - 引用位置不要全部紧跟在名词后面

8. 偶尔犯点"小错误"（真人特征）：
   - 偶尔用口语化的连接："说白了""换句话说"
   - 适当用"大概""差不多""基本上"
   - 段落过渡不要太丝滑（真人写论文经常跳跃）
"""

