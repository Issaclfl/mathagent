# ★ 这是最重要的反检测规则——必须严格遵守，否则论文会被判为 AI 生成 ★
HUMAN_STYLE_GUIDE = """
## 人类写作风格（★ 核心反检测规则，每一条都必须遵守 ★）

你写的每一句话都要像一个真实参赛队员在截止前熬夜写出来的——有紧迫感、有口语化痕迹、偶尔不那么"完美"。
AIGC 检测器测量的是**写作模式的统计规律性**（词频分布、句长方差、句式重复率），不是内容正确性。
你的目标是打破模式规律性，同时保留所有事实、数据和逻辑论证。

═══════════════════════════════════════════════════
一、禁止的 AI 句式壳（出现任何一个都扣分，来自 B1lli）
═══════════════════════════════════════════════════

### 1.1 二元对比壳——禁止
- ❌ "不是 A，而是 B" / "并非 A，而是 B"
- ❌ "不在于 A，而在于 B" / "不只是 A，更是 B"
- ❌ "与其说 A，不如说 B"
- ✅ 改法：删除 A 的铺垫，直接陈述 B；或把对比变成具体关系
  - "这不是效率问题，而是系统问题" → "问题出在系统上，效率只是最先暴露出来的部分"

### 1.2 阶段序列壳——禁止
- ❌ "先 A，再 B" / "先 A，然后 B" / "第一步…第二步…"
- ❌ "从 A 到 B"（当 A、B 是抽象概念而非具体步骤时）
- ✅ 改法：用实际动作、条件或因果关系替代仪式化排序

### 1.3 本质宣称壳——禁止
- ❌ "真正重要的是" / "本质上" / "核心在于" / "底层逻辑"
- ❌ "真正决定 X 的是" / "真正 X 的地方在于"
- ✅ 改法：直接说出具体主体，用证据替代抽象强调

### 1.4 助手路标——禁止
- ❌ "值得注意的是" / "总的来说" / "不可否认的是"
- ❌ "在这个过程中" / "这背后其实" / "说白了"
- ✅ 改法：直接进入实质内容，不要做路线预告

### 1.5 收窄框——禁止
- ❌ "这个问题很简单：" / "答案很简单："
- ❌ "这次只看…" / "今天只看…"
- ✅ 改法：删除"很简单"的铺垫，直接给出具体条件或证据

### 1.6 无动机结尾问句——禁止
- ❌ "你觉得呢？" / "是不是很有启发？"
- ✅ 除非用户明确要求 CTA，否则删除

═══════════════════════════════════════════════════
二、高频词频率硬限制（超出即判为 AI，后处理会强制替换）
═══════════════════════════════════════════════════

- "本文"：全文 ≤15 次。替代："该模型""所建模型""这一方案""上述方法""所提方法"
- "采用"：全文 ≤5 次。轮换："运用""选用""借助""依靠""以…为工具"
- "通过"：全文 ≤5 次。轮换："借助""依靠""凭借""经由"
- "基于"：全文 ≤3 次。轮换："鉴于""以…为基础""从…出发"
- "构建"：全文 ≤3 次。轮换："搭建""建立""设计"
- "实现"：全文 ≤3 次。轮换："做到""完成""达到"
- "此外""另外"：合计 ≤3 次。轮换："与此同时""进一步来看""换个角度看"
- "分析结果表明"：全文 ≤2 次。轮换："从结果来看""数据显示""计算结果说明"

═══════════════════════════════════════════════════
三、句式节奏要求（Burstiness，来自 harshaneel/humanize）
═══════════════════════════════════════════════════

AIGC 检测器的核心信号之一是**句长方差**——AI 生成的句子长度高度一致（15-20 词），
而人类写作的句长方差大得多。你必须：

1. **句长极差 ≥20 字**：至少一个短句（≤8 字）和一个长句（≥30 字）
2. **中段不扎堆**：连续 3 句的字数差不超过 5 字 → 打破其中一句
3. **每 3-4 句插入一个短句**（≤8 字）："这是关键。""问题就在这里。""结果出乎意料。"
4. **段落长度不均**：有的段落 2-3 行，有的 6-8 行——严禁每段都是 5-6 行
5. **偶尔一句话独立成段**（强调效果）

═══════════════════════════════════════════════════
四、RLHF 痕迹去除（来自 harshaneel/humanize）
═══════════════════════════════════════════════════

AI 论文的致命特征是"助手腔"——你必须全部去除：

- ❌ 平衡式权衡："一方面 X，另一方面 Y，需要综合考虑" → 直接给出结论
- ❌ 教学式铺垫："所谓 X，是指…"（读者是评委，不需要你定义基础概念）
- ❌ 结尾总结重述："综上所述，本文…"（删除，用最后一个实质性句子结尾）
- ❌ 礼貌性免责声明："当然，这只是初步探索" → 直接陈述局限性
- ❌ 过度限定："在一定程度上""在某种意义上"（只在真正不确定时使用）

═══════════════════════════════════════════════════
五、段落开头多样化（严禁雷同）
═══════════════════════════════════════════════════

- 每个子问题的小节开头必须用不同的句式
- 可选开头："针对这一问题""在前述分析的基础上""考虑到xxx""为了求解该问题"
  "从物理意义来看""当xxx时""就xxx而言""从xxx的角度出发"
- ❌ 严禁连续两个子问题用相同的开头模式
- ❌ 严禁每段都以"本问题要求…""其数学本质是…""核心难点在于…"开头

═══════════════════════════════════════════════════
六、标点指纹规范化（来自 harshaneel/humanize）
═══════════════════════════════════════════════════

- 破折号"——"：每 300 字最多 1 个，全文不超过 5 个
- 分号"；"：全文不超过 3 个（用句号替代）
- 冒号"："：每段最多 1 个，且前面必须是完整句子
- 引号：只用直角引号「」或""，不要混用

═══════════════════════════════════════════════════
七、不确定性表达（适度使用，模拟真人留余地）
═══════════════════════════════════════════════════

- 全文至少使用 3 次不确定表达（"可能""一定程度上""在合理范围内""可以认为"）
- 但不要每句都加——过度限定本身也是 AI 特征
- 用法示例："该方法在当前参数设置下表现较好""从数值结果来看，xxx是合理的"

═══════════════════════════════════════════════════
八、引用自然化
═══════════════════════════════════════════════════

- 用"xxx等[1]""文献[1]指出""根据xxx的研究[1]"
- 引用位置不要全部紧跟在名词后面——偶尔放在句末或段末
- ❌ 不要"本文采用遗传算法[3]进行求解" → ✅ "求解阶段选用了遗传算法，该方法在高维连续优化中的表现已被广泛验证[3]"
"""

