# 论文整体结构规范（参考 2025A 优秀论文范例）
STRUCTURE_GUIDE = """\
【论文整体结构规范】★ 参考获国家奖的优秀论文结构 ★

一篇规范的高分数模论文应包含以下章节（按序）：
1. 摘要（单独成页，150-250字，核心）
2. 问题的提出（精炼重述题目，1页以内，直接列出各子问题）
3. 模型的建立（含假设、符号、公式推导，按子问题分节）
4. 模型的求解与结果（算法、计算、结果表格）
5. 灵敏度分析（选2-3个关键参数扰动，验证鲁棒性）
6. 模型的评价与推广（优点/缺点/推广，简短）
7. 参考文献（GB/T 7714 格式）

★ 关键结构调整（参考优秀论文）★
- **合并"问题重述"+"问题分析"为"问题的提出"**：
  不要单独的"问题分析"章节！优秀论文的"问题的提出"就是精炼重述题目背景，
  然后直接列出各子问题（每题1段，3-5句），不做"核心难点分析""技术路线"等展开。
  分析内容融入后续的模型建立中。
- **删除独立"模型假设"章节**：
  优秀论文没有独立的"模型假设"！假设融入模型描述中（如"忽略空气阻力，干扰弹
  仅受重力作用"直接写在运动方程前面）。不要单独列5-8条假设。
- **数学公式从第2页开始**：
  优秀论文第2页就是运动方程。我们的论文第6页才开始有公式——太晚了。
  "问题的提出"之后立即进入模型建立，直接写公式。

【篇幅控制——必须严格遵守】
- "问题的提出"：≤1页（约300-400字），背景2-3段 + 各子问题各1段
- "模型的建立"：核心章节，每个子问题3-5页，公式密集
- "灵敏度分析"：1-2页
- "模型评价"：0.5页
- 全文控制在8-12页（不含参考文献）

【公式规范】
- 每个独立公式（$$...$$块）由系统统一连续编号 (1),(2),...，正文**不要**手写具体式号
- 正文引用公式时用"上式""前述公式"等表述
- 公式前后各空一行；首次出现的公式需附文字说明各变量含义
- **公式要密集**：每个子问题至少3-5个核心公式，不要用大段文字描述数学关系

【结果呈现规范】
- 每个子问题求解结束后，用汇总表格呈现最优方案（决策变量 | 最优值）
- 多子问题之间存在递进关系时，做对比分析
- 结果表格要简洁，每个子问题1-2个表格

【语言与排版规范】
- 全文使用第三人称或无人称表述
- 数值保留适当小数位（长度精确到0.1，时间精确到0.01）
- 每个子问题的小节标题格式统一，不自行编号

【输出纪律——必须严格遵守】
- 只输出论文正文内容，**禁止**输出任何设计思路、元评论或自我解释
- **禁止**出现："符号设计说明与反思"、"我将..."、"我选择...因为..."、"写作思路"、"反思"
- 直接陈述内容，不使用自我指涉性过渡语
"""

# 摘要写作规范（从 RGV 范例摘要提炼）
ABSTRACT_GUIDE = """\
【摘要写作规范】目标：150-250字内让评委看懂你做了什么、得到什么。

★ 篇幅限制：摘要总字数 150-250 字，超过 250 字直接不合格 ★

结构：
1. 开篇一句：本文针对【XX问题】，建立了【XX模型】（1 句，不超过 2 句）
2. 分小题说明：每个子问题**只用一句话**概述方法和结果
   - 格式："针对问题X，采用【方法】，得到【具体数值结果】"
   - 每问 1 句，不要展开方法细节
3. 结尾：一句话总结模型优点
4. 最后单独一行输出关键词：3-5个，格式"关键词：XXX、XXX、XXX"

★ 禁止事项 ★
- ❌ 禁止出现变量符号（t、θ、v、T、Δt 等），全部用文字描述
- ❌ 禁止出现公式编号引用（如"式(5)"）
- ❌ 禁止对每个子问题展开方法描述（"首先建立了…然后采用了…"）
- ❌ 禁止摘要超过 250 字
"""

